#!/usr/bin/env python3
"""
WGCNA Co-expression Network Integration for GRBV Transcriptomics.

Reads pre-computed WGCNA results (module eigengenes from MEs.csv and
gene-to-module assignments from Module_genes.xlsx) generated by the
R WGCNA pipeline (WGCNA.Rmd) and produces publication-quality figures
matching the pipeline matplotlib style.

Analyses:
  - Module-trait correlation heatmap (infection, season, stage, YSI)
  - Module eigengene expression profiles across conditions
  - Hub gene heatmaps per module
  - Module enrichment for GRBV DEGs

Outputs:
  - Fig 53: Module-trait correlation heatmap
  - Fig 54: Module eigengene profiles across conditions
  - Fig 55: Hub gene heatmaps and module DEG enrichment
  - coexpression_modules.csv
  - module_trait_correlations.csv
  - hub_genes_per_module.csv
"""

import pandas as pd
import numpy as np
import sqlite3
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import matplotlib.gridspec as gridspec
import seaborn as sns
from scipy import stats
from scipy.stats import rankdata, spearmanr, pearsonr, fisher_exact
from collections import defaultdict
import textwrap
import warnings
warnings.filterwarnings('ignore')

plt.rcParams.update({
    'figure.dpi': 300, 'font.size': 15, 'axes.titlesize': 16,
    'axes.labelsize': 15, 'figure.facecolor': 'white'
})

# ============================================================
# 1. LOAD WGCNA OUTPUTS
# ============================================================
print("=" * 70)
print("CO-EXPRESSION NETWORK ANALYSIS: LOADING WGCNA RESULTS")
print("=" * 70)

# Module eigengenes
mes = pd.read_csv('MEs.csv')
print(f"Module eigengenes: {mes.shape[0]} samples × {mes.shape[1]} columns")
print(f"Columns: {list(mes.columns)}")

# Identify module columns (ME prefix)
me_cols = [c for c in mes.columns if c.startswith('ME') and c != 'MEgrey']
module_names = [c.replace('ME', '') for c in me_cols]
n_modules = len(me_cols)
print(f"Modules (excl. grey): {n_modules} — {module_names}")

# Module gene assignments
module_genes = {}
try:
    xls = pd.ExcelFile('Module_genes.xlsx')
    sheet_names = xls.sheet_names
    print(f"\nModule sheets: {sheet_names}")

    for sheet in sheet_names:
        df = pd.read_excel('Module_genes.xlsx', sheet_name=sheet)
        gene_col = 'Gene.stable.ID' if 'Gene.stable.ID' in df.columns else df.columns[0]
        genes = df[gene_col].dropna().tolist()
        module_genes[sheet] = genes
        print(f"  {sheet}: {len(genes)} genes")
except Exception as e:
    print(f"Error loading Module_genes.xlsx: {e}")

# Total genes
total_module_genes = sum(len(g) for g in module_genes.values())
print(f"\nTotal genes across modules: {total_module_genes}")


# ============================================================
# 2. LOAD EXPRESSION DATA AND COMPUTE DE
# ============================================================
print("\n" + "=" * 70)
print("LOADING EXPRESSION DATA FOR DEG OVERLAY")
print("=" * 70)

counts = pd.read_csv('counts_matrix.txt', sep='\t', index_col=0)
meta = pd.read_csv('sample_metadata.txt', sep='\t')

common_samples = list(set(counts.columns) & set(meta['Sample']))
counts = counts[common_samples]
meta = meta[meta['Sample'].isin(common_samples)].set_index('Sample').loc[common_samples]

min_samples = int(0.1 * counts.shape[1])
gene_mask = (counts >= 10).sum(axis=1) >= min_samples
counts_filtered = counts.loc[gene_mask]

lib_sizes = counts_filtered.sum(axis=0)
cpm = counts_filtered.div(lib_sizes, axis=1) * 1e6
log_cpm = np.log2(cpm + 1)

expressed = set(log_cpm.index)
print(f"Expressed genes: {len(expressed)}")

# Compute pooled DE for DEG overlay
print("Computing pooled DE...")
infected = meta[meta['Infection_Group'] == 'RB(+)'].index.tolist()
control = meta[meta['Infection_Group'] == 'RB(-)'].index.tolist()

de_results = []
for gene in log_cpm.index:
    v1 = log_cpm.loc[gene, infected].values
    v2 = log_cpm.loc[gene, control].values
    if np.std(v1) == 0 and np.std(v2) == 0:
        continue
    t, p = stats.ttest_ind(v1, v2, equal_var=False)
    de_results.append({'gene': gene, 'log2FC': v1.mean() - v2.mean(), 'pvalue': p})

de_df = pd.DataFrame(de_results)
de_df['padj'] = np.minimum(de_df['pvalue'] * len(de_df) / rankdata(de_df['pvalue']), 1.0)
pooled_degs = set(de_df[(de_df['padj'] < 0.05) & (de_df['log2FC'].abs() >= 1)]['gene'])
pooled_up = set(de_df[(de_df['padj'] < 0.05) & (de_df['log2FC'] >= 1)]['gene'])
pooled_down = set(de_df[(de_df['padj'] < 0.05) & (de_df['log2FC'] <= -1)]['gene'])
print(f"Pooled DEGs: {len(pooled_degs)} (up={len(pooled_up)}, down={len(pooled_down)})")

# Gene names
conn = sqlite3.connect('org.Vvinifera.eg.db/inst/extdata/org.Vvinifera.eg.sqlite')
gene_info = pd.read_sql("SELECT SYMBOL, GENENAME FROM gene_info", conn)
gene_name_map = dict(zip(gene_info['SYMBOL'], gene_info['GENENAME']))
conn.close()


# ============================================================
# 3. MODULE-TRAIT CORRELATIONS
# ============================================================
print("\n" + "=" * 70)
print("COMPUTING MODULE-TRAIT CORRELATIONS")
print("=" * 70)

# Encode traits as numeric
trait_df = mes[['sample', 'group', 'stage', 'season']].copy()

# Infection: RB vs Uninfected
trait_df['Infection'] = trait_df['group'].apply(
    lambda x: 1 if 'RB' in str(x) and 'Uninfected' not in str(x) else 0)

# Season: 2021=0, 2022=1
trait_df['Season_num'] = trait_df['season'].apply(lambda x: 0 if str(x) == '2021' else 1)

# Stage: ordinal encoding
stage_map = {'Pre_veraison': 0, 'Veraison': 1, 'Post_veraison': 2, 'Harvest': 3}
trait_df['Stage_num'] = trait_df['stage'].map(stage_map)

# YSI: extract from group
def extract_ysi(g):
    g = str(g)
    if 'Uninfected' in g:
        return 0
    for yr in ['2016', '2017', '2018', '2019', '2020', '2021', '2022']:
        if yr in g:
            return int(yr)
    return np.nan
trait_df['YSI'] = trait_df['group'].apply(extract_ysi)

traits = ['Infection', 'Season_num', 'Stage_num', 'YSI']
trait_labels = ['GRBV\nInfection', 'Season\n(2021→2022)', 'Maturity\nStage', 'Infection\nYear']

# Compute correlations
corr_matrix = pd.DataFrame(index=me_cols, columns=traits, dtype=float)
pval_matrix = pd.DataFrame(index=me_cols, columns=traits, dtype=float)

for me_col in me_cols:
    me_vals = mes[me_col].values
    for trait in traits:
        t_vals = trait_df[trait].values
        valid = ~np.isnan(t_vals)
        if valid.sum() < 10:
            corr_matrix.loc[me_col, trait] = 0
            pval_matrix.loc[me_col, trait] = 1
            continue
        r, p = pearsonr(me_vals[valid], t_vals[valid])
        corr_matrix.loc[me_col, trait] = r
        pval_matrix.loc[me_col, trait] = p

# Save
corr_out = corr_matrix.copy()
corr_out.index = [c.replace('ME', '') for c in corr_out.index]
corr_out.columns = ['Infection', 'Season', 'Stage', 'InfectionYear']
corr_out.to_csv('module_trait_correlations.csv')
print(f"Saved module_trait_correlations.csv")

print("\nModule-Trait Correlations (Pearson r):")
for me_col in me_cols:
    module = me_col.replace('ME', '')
    line = f"  {module:15s}"
    for trait, label in zip(traits, ['Inf', 'Sea', 'Stg', 'YSI']):
        r = corr_matrix.loc[me_col, trait]
        p = pval_matrix.loc[me_col, trait]
        sig = '***' if p < 0.001 else '**' if p < 0.01 else '*' if p < 0.05 else ''
        line += f"  {label}={r:+.3f}{sig}"
    print(line)


# ============================================================
# 4. MODULE DEG ENRICHMENT
# ============================================================
print("\n" + "=" * 70)
print("MODULE DEG ENRICHMENT ANALYSIS")
print("=" * 70)

module_stats = []
for module, genes in module_genes.items():
    if module == 'grey':
        continue
    gene_set = set(genes) & expressed
    n_module = len(gene_set)
    n_deg = len(gene_set & pooled_degs)
    n_up = len(gene_set & pooled_up)
    n_down = len(gene_set & pooled_down)

    # Fisher enrichment
    a = n_deg
    b = len(pooled_degs) - a
    c = n_module - a
    d = len(expressed) - len(pooled_degs) - c
    if a + c > 0:
        _, pval = fisher_exact([[a, b], [c, d]], alternative='greater')
    else:
        pval = 1.0

    module_stats.append({
        'module': module,
        'n_genes': len(genes),
        'n_expressed': n_module,
        'n_deg': n_deg,
        'n_up': n_up,
        'n_down': n_down,
        'pct_deg': n_deg / n_module * 100 if n_module > 0 else 0,
        'enrichment_pval': pval,
        'direction_bias': 'UP' if n_up > n_down else 'DOWN' if n_down > n_up else 'MIXED',
    })

module_stats_df = pd.DataFrame(module_stats)
module_stats_df.to_csv('coexpression_modules.csv', index=False)
print(f"Saved coexpression_modules.csv")

for _, row in module_stats_df.iterrows():
    sig = '*' if row['enrichment_pval'] < 0.05 else ''
    print(f"  {row['module']:15s}: {row['n_genes']:4d} genes, {row['n_deg']:3d} DEGs "
          f"({row['pct_deg']:.1f}%), {row['direction_bias']:5s} {sig}")


# ============================================================
# 5. IDENTIFY HUB GENES PER MODULE
# ============================================================
print("\n" + "=" * 70)
print("IDENTIFYING HUB GENES PER MODULE")
print("=" * 70)

hub_rows = []
for module, genes in module_genes.items():
    if module == 'grey':
        continue

    me_col = f'ME{module}'
    if me_col not in mes.columns:
        continue

    me_vals = mes[me_col].values

    # Find hub genes: correlate each gene's expression with module eigengene
    gene_cors = []
    for gene in genes:
        if gene in log_cpm.index:
            # Match samples between MEs and log_cpm
            common = [s for s in mes['sample'] if s in log_cpm.columns]
            if len(common) < 20:
                continue
            me_sub = mes[mes['sample'].isin(common)].set_index('sample').loc[common][me_col].values
            gene_expr = log_cpm.loc[gene, common].values
            r, p = pearsonr(gene_expr, me_sub)
            gene_cors.append({
                'module': module,
                'gene': gene,
                'gene_name': gene_name_map.get(gene, ''),
                'kME': r,
                'kME_pval': p,
                'is_deg': gene in pooled_degs,
                'log2FC': de_df[de_df['gene'] == gene]['log2FC'].values[0] if gene in de_df['gene'].values else 0,
            })

    gene_cors = sorted(gene_cors, key=lambda x: abs(x['kME']), reverse=True)

    # Top 10 hub genes
    for g in gene_cors[:10]:
        g['hub_rank'] = gene_cors.index(g) + 1
        hub_rows.append(g)

    if gene_cors:
        top = gene_cors[0]
        print(f"  {module:15s}: top hub = {top['gene']} ({top['gene_name'][:30]}) kME={top['kME']:.3f}")

hub_df = pd.DataFrame(hub_rows)
hub_df.to_csv('hub_genes_per_module.csv', index=False)
print(f"\nSaved hub_genes_per_module.csv ({len(hub_df)} hub genes)")


# ============================================================
# 6. FIGURE 53 — Module-Trait Correlation Heatmap
# ============================================================
print("\n" + "=" * 70)
print("PLOTTING FIGURE 53: MODULE-TRAIT CORRELATION HEATMAP")
print("=" * 70)

fig, axes = plt.subplots(1, 2, figsize=(20, 10))
fig.suptitle('WGCNA Module-Trait Correlations',
             fontsize=20, fontweight='bold', y=0.98)

# Panel A: Correlation heatmap
ax = axes[0]

# Sort modules by infection correlation
sort_order = corr_matrix['Infection'].astype(float).sort_values(ascending=False).index
sorted_corr = corr_matrix.loc[sort_order].astype(float)
sorted_pval = pval_matrix.loc[sort_order].astype(float)

module_labels = [c.replace('ME', '') for c in sort_order]

# Create annotation text with r (p)
annot = np.empty_like(sorted_corr.values, dtype=object)
for i in range(sorted_corr.shape[0]):
    for j in range(sorted_corr.shape[1]):
        r = float(sorted_corr.iloc[i, j])
        p = float(sorted_pval.iloc[i, j])
        if p < 0.001:
            annot[i, j] = f'{r:.2f}\n***'
        elif p < 0.01:
            annot[i, j] = f'{r:.2f}\n**'
        elif p < 0.05:
            annot[i, j] = f'{r:.2f}\n*'
        else:
            annot[i, j] = f'{r:.2f}'

sns.heatmap(sorted_corr.values.astype(float), ax=ax,
            xticklabels=trait_labels, yticklabels=module_labels,
            cmap='RdBu_r', center=0, vmin=-0.5, vmax=0.5,
            annot=annot, fmt='',
            linewidths=0.5, linecolor='white',
            cbar_kws={'label': 'Pearson r', 'shrink': 0.7})

# Color module labels by module color
for i, label in enumerate(module_labels):
    try:
        ax.get_yticklabels()[i].set_color(label)
        ax.get_yticklabels()[i].set_fontweight('bold')
    except Exception:
        pass

ax.set_title('A. Module-Trait Correlations', fontsize=16, fontweight='bold')
ax.tick_params(axis='y', labelsize=11)
ax.tick_params(axis='x', labelsize=12)

# Panel B: Module size and DEG enrichment
ax = axes[1]

# Sort by n_genes
stats_sorted = module_stats_df.sort_values('n_genes', ascending=True)
y = np.arange(len(stats_sorted))

# Bar chart: module size
bars = ax.barh(y, stats_sorted['n_genes'], color=[m for m in stats_sorted['module']],
               alpha=0.7, edgecolor='black', linewidth=0.5)

# Overlay DEG count
ax.barh(y, stats_sorted['n_deg'], color='red', alpha=0.5, label='DEGs')

ax.set_yticks(y)
ax.set_yticklabels(stats_sorted['module'], fontsize=11)
ax.set_xlabel('Number of genes', fontsize=14)
ax.set_title('B. Module Size & DEG Content', fontsize=16, fontweight='bold')

# Annotate enrichment significance
for i, (_, row) in enumerate(stats_sorted.iterrows()):
    sig = '***' if row['enrichment_pval'] < 0.001 else '**' if row['enrichment_pval'] < 0.01 else '*' if row['enrichment_pval'] < 0.05 else ''
    ax.text(row['n_genes'] + 10, i, f"{row['n_deg']} DEGs ({row['pct_deg']:.0f}%) {sig}",
            va='center', fontsize=9)

ax.legend(fontsize=11, loc='lower right')

plt.tight_layout(rect=[0, 0, 1, 0.95])
plt.savefig('53_module_trait_correlations.png', dpi=300, bbox_inches='tight')
plt.close()
print("Saved 53_module_trait_correlations.png")


# ============================================================
# 7. FIGURE 54 — Module Eigengene Profiles
# ============================================================
print("\n" + "=" * 70)
print("PLOTTING FIGURE 54: MODULE EIGENGENE PROFILES")
print("=" * 70)

# Select top modules most correlated with infection or season
infection_corrs = corr_matrix['Infection'].astype(float).abs().sort_values(ascending=False)
top_modules = infection_corrs.head(6).index.tolist()

fig, axes = plt.subplots(2, 3, figsize=(24, 14))
fig.suptitle('Module Eigengene Expression Profiles Across Conditions',
             fontsize=20, fontweight='bold', y=0.98)

stages = ['Pre_veraison', 'Veraison', 'Post_veraison', 'Harvest']
stage_labels_short = {'Pre_veraison': 'Pre-vér', 'Veraison': 'Véraison',
                      'Post_veraison': 'Post-vér', 'Harvest': 'Harvest'}

for idx, me_col in enumerate(top_modules):
    ax = axes[idx // 3, idx % 3]
    module = me_col.replace('ME', '')

    # Plot mean eigengene across stage for each group
    for season, ls in [('2021', '-'), ('2022', '--')]:
        for inf_label, color in [('RB', '#e74c3c'), ('Uninfected', '#2980b9')]:
            means = []
            sems = []
            for stage in stages:
                mask = (mes['season'].astype(str) == str(season)) & \
                       (mes['stage'] == stage)
                if inf_label == 'RB':
                    mask &= mes['group'].str.contains('RB') & ~mes['group'].str.contains('Uninfected')
                else:
                    mask &= mes['group'].str.contains('Uninfected')

                vals = mes.loc[mask, me_col]
                if len(vals) > 0:
                    means.append(vals.mean())
                    sems.append(vals.sem())
                else:
                    means.append(np.nan)
                    sems.append(0)

            label_str = f"{season} {'Infected' if inf_label == 'RB' else 'Control'}"
            ax.errorbar(range(4), means, yerr=sems,
                       marker='o', linestyle=ls, color=color,
                       label=label_str, markersize=5, linewidth=1.5, capsize=3)

    r_inf = float(corr_matrix.loc[me_col, 'Infection'])
    p_inf = float(pval_matrix.loc[me_col, 'Infection'])
    ax.set_title(f'{module} module\n(r_inf={r_inf:+.3f}, p={p_inf:.2e})',
                fontsize=13, fontweight='bold')
    ax.set_xticks(range(4))
    ax.set_xticklabels([stage_labels_short[s] for s in stages], fontsize=10)
    ax.set_ylabel('Module Eigengene', fontsize=12)
    ax.axhline(0, color='grey', linewidth=0.5, linestyle='--')

    if idx == 0:
        ax.legend(fontsize=8, loc='best')

plt.tight_layout(rect=[0, 0, 1, 0.95])
plt.savefig('54_module_eigengene_profiles.png', dpi=300, bbox_inches='tight')
plt.close()
print("Saved 54_module_eigengene_profiles.png")


# ============================================================
# 8. FIGURE 55 — Hub Gene Heatmaps + Module Enrichment
# ============================================================
print("\n" + "=" * 70)
print("PLOTTING FIGURE 55: HUB GENES & MODULE ENRICHMENT")
print("=" * 70)

fig, axes = plt.subplots(2, 3, figsize=(24, 16))
fig.suptitle('Hub Gene Expression Across Conditions',
             fontsize=20, fontweight='bold', y=0.98)

# Show hub genes for top 6 infection-correlated modules
for idx, me_col in enumerate(top_modules):
    ax = axes[idx // 3, idx % 3]
    module = me_col.replace('ME', '')

    # Get hub genes for this module
    module_hubs = hub_df[hub_df['module'] == module].head(8)

    if len(module_hubs) == 0:
        ax.text(0.5, 0.5, f'{module}\nNo hub genes', ha='center', va='center',
                transform=ax.transAxes, fontsize=12)
        ax.set_title(module, fontsize=14, fontweight='bold')
        continue

    # Build heatmap: hub genes × conditions
    hub_gene_list = module_hubs['gene'].tolist()
    hub_gene_labels = []
    for g in hub_gene_list:
        gname = gene_name_map.get(g, '')[:25]
        is_deg = '★' if g in pooled_degs else ''
        hub_gene_labels.append(f"{g} {is_deg}\n({gname})")

    # Mean expression for each condition
    condition_labels = []
    expr_matrix = []
    for season in ['2021', '2022']:
        for stage in stages:
            for inf in ['Infected', 'Control']:
                if inf == 'Infected':
                    mask = (mes['season'].astype(str) == str(season)) & \
                           (mes['stage'] == stage) & \
                           mes['group'].str.contains('RB') & ~mes['group'].str.contains('Uninfected')
                else:
                    mask = (mes['season'].astype(str) == str(season)) & \
                           (mes['stage'] == stage) & \
                           mes['group'].str.contains('Uninfected')

                samples = mes.loc[mask, 'sample'].tolist()
                common = [s for s in samples if s in log_cpm.columns]

                if len(common) > 0 and all(g in log_cpm.index for g in hub_gene_list):
                    means = log_cpm.loc[hub_gene_list, common].mean(axis=1).values
                    expr_matrix.append(means)
                    condition_labels.append(f"{season}\n{stage_labels_short.get(stage, stage)[:6]}\n{inf[:3]}")

    if expr_matrix:
        expr_arr = np.array(expr_matrix).T  # genes × conditions
        # Z-score per gene
        expr_z = (expr_arr - expr_arr.mean(axis=1, keepdims=True))
        row_std = expr_arr.std(axis=1, keepdims=True)
        row_std[row_std == 0] = 1
        expr_z = expr_z / row_std

        sns.heatmap(expr_z, ax=ax,
                    yticklabels=hub_gene_labels, xticklabels=condition_labels,
                    cmap='RdBu_r', center=0,
                    linewidths=0.3, linecolor='white',
                    cbar_kws={'shrink': 0.5, 'label': 'Z-score'})
        ax.set_title(f'{module} module hub genes', fontsize=13, fontweight='bold',
                    color=module if module in ['red', 'blue', 'green', 'brown', 'yellow',
                                                'black', 'pink', 'purple', 'magenta',
                                                'turquoise', 'salmon', 'tan'] else 'black')
        ax.tick_params(axis='y', labelsize=7)
        ax.tick_params(axis='x', labelsize=6, rotation=45)
    else:
        ax.text(0.5, 0.5, f'{module}\nNo expression data', ha='center', va='center',
                transform=ax.transAxes, fontsize=12)

plt.tight_layout(rect=[0, 0, 1, 0.95])
plt.savefig('55_hub_gene_heatmaps.png', dpi=300, bbox_inches='tight')
plt.close()
print("Saved 55_hub_gene_heatmaps.png")


# ============================================================
# SUMMARY
# ============================================================
print("\n" + "=" * 70)
print("CO-EXPRESSION NETWORK ANALYSIS COMPLETE")
print("=" * 70)

print(f"\nWGCNA modules: {n_modules} (excl. grey)")
print(f"Total genes in modules: {total_module_genes}")
print(f"Hub genes identified: {len(hub_df)}")

print(f"\nTop infection-correlated modules:")
for me_col in top_modules[:5]:
    module = me_col.replace('ME', '')
    r = float(corr_matrix.loc[me_col, 'Infection'])
    p = float(pval_matrix.loc[me_col, 'Infection'])
    n_genes = len(module_genes.get(module, []))
    print(f"  {module:15s}: r={r:+.3f} (p={p:.2e}), {n_genes} genes")

print(f"\nOutput files:")
print(f"  - 53_module_trait_correlations.png")
print(f"  - 54_module_eigengene_profiles.png")
print(f"  - 55_hub_gene_heatmaps.png")
print(f"  - coexpression_modules.csv")
print(f"  - module_trait_correlations.csv")
print(f"  - hub_genes_per_module.csv")
